/* =====================================================================
 * util.js ― アプリ全体で使う小さな共通関数をまとめたファイル
 *
 * ここにある関数は画面やデータベースに依存しない「純粋な道具」です。
 *   ・ID の発行
 *   ・HTML に埋め込む文字の無害化（エスケープ）
 *   ・よみがなの整形（カタカナ→ひらがな、並べ替え用のキー作成）
 *   ・ISBN の検証と変換
 *   ・ジャンル名から色を決める処理
 * ===================================================================== */

const Util = {
  /* ---------------------------------------------------------------
   * 一意な ID を作る。
   * 本や写真 1 件ごとの識別子として使う。
   * 「現在時刻（36進数）＋乱数」なので、個人利用の件数で重複することはない。
   * --------------------------------------------------------------- */
  uid() {
    return Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
  },

  /* ---------------------------------------------------------------
   * HTML に文字列を埋め込む前に、記号を安全な表記へ置き換える。
   * 題名に < や & が入っていても画面が壊れないようにするための処理。
   * --------------------------------------------------------------- */
  esc(value) {
    return String(value == null ? '' : value)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  },

  /* ---------------------------------------------------------------
   * カタカナをひらがなに変換する。
   * 文字コード上、カタカナ（ァ〜ヶ）から 0x60 を引くと対応するひらがなになる。
   * --------------------------------------------------------------- */
  kataToHira(text) {
    return String(text || '').replace(/[\u30A1-\u30F6]/g, (ch) =>
      String.fromCharCode(ch.charCodeAt(0) - 0x60)
    );
  },

  /* ---------------------------------------------------------------
   * よみがなを「保存・表示用」に整える。
   * NDLサーチの読みは「ボッチ ・ ザ ・ ロック」のように
   * カタカナ＋単語ごとの空白で返ってくるので、
   * ひらがなに直し、空白を取り除いて 1 つながりにする。
   * --------------------------------------------------------------- */
  cleanYomi(text) {
    return Util.kataToHira(String(text || '').normalize('NFKC'))
      .replace(/\s+/g, '')
      .trim();
  },

  /* ---------------------------------------------------------------
   * 五十音順の比較に使う「並べ替えキー」を作る。
   * よみがながあればそれを、無ければ題名を使う。
   * 記号や空白は順番に影響しないよう取り除く。
   * --------------------------------------------------------------- */
  sortKey(book) {
    const base = book.titleYomi || book.title || '';
    return Util.kataToHira(base.normalize('NFKC'))
      .toLowerCase()
      .replace(/[\s・･!！?？「」『』（）()［］\[\]〈〉《》、。,.:：;；\-―—~〜]/g, '');
  },

  /* ---------------------------------------------------------------
   * 検索用に文字列をそろえる。
   * 全角/半角・大文字/小文字・カタカナ/ひらがなの違いを無視して
   * 一致判定できるようにする。
   * --------------------------------------------------------------- */
  searchText(text) {
    return Util.kataToHira(String(text || '').normalize('NFKC'))
      .toLowerCase()
      .replace(/\s+/g, '');
  },

  /* ---------------------------------------------------------------
   * ISBN-13 の検査数字（最後の 1 桁）が正しいかを調べる。
   * 先頭から「×1, ×3, ×1, ×3 …」と重みを掛けた合計が
   * 10 の倍数になれば正しい番号。
   * バーコードの読み間違いを弾くために使う。
   * --------------------------------------------------------------- */
  isValidIsbn13(code) {
    if (!/^\d{13}$/.test(code)) return false;
    let sum = 0;
    for (let i = 0; i < 13; i++) {
      sum += Number(code[i]) * (i % 2 === 0 ? 1 : 3);
    }
    return sum % 10 === 0;
  },

  /* ---------------------------------------------------------------
   * 古い 10 桁の ISBN を 13 桁に変換する。
   * 先頭に 978 を付け、最後の検査数字を計算し直す。
   * --------------------------------------------------------------- */
  isbn10to13(isbn10) {
    const body = '978' + isbn10.slice(0, 9);
    let sum = 0;
    for (let i = 0; i < 12; i++) {
      sum += Number(body[i]) * (i % 2 === 0 ? 1 : 3);
    }
    const check = (10 - (sum % 10)) % 10;
    return body + String(check);
  },

  /* ---------------------------------------------------------------
   * 入力された ISBN（ハイフン付き・10桁・13桁など）を
   * ハイフン無しの 13 桁にそろえる。
   * ISBN として成り立たない場合は null を返す。
   * --------------------------------------------------------------- */
  normalizeIsbn(raw) {
    const s = String(raw || '').normalize('NFKC').replace(/[^0-9Xx]/g, '').toUpperCase();
    if (/^\d{9}[\dX]$/.test(s)) {
      return Util.isbn10to13(s);
    }
    if (/^97[89]\d{10}$/.test(s) && Util.isValidIsbn13(s)) {
      return s;
    }
    return null;
  },

  /* ---------------------------------------------------------------
   * ジャンル名から色（色相）を決める。
   * 同じジャンル名なら毎回同じ色になるよう、文字コードから数値を作っている。
   * 一覧の左端に出す「背表紙の帯」の色に使う。
   * --------------------------------------------------------------- */
  genreHue(name) {
    if (!name) return null; // 未分類は色なし（灰色）
    let hash = 0;
    for (const ch of name) {
      hash = (hash * 31 + ch.codePointAt(0)) % 360;
    }
    return hash;
  },

  /* ---------------------------------------------------------------
   * 日時（ミリ秒の数値）を「2026/11/13」の形にする。
   * --------------------------------------------------------------- */
  formatDate(ms) {
    if (!ms) return '';
    const d = new Date(ms);
    return `${d.getFullYear()}/${d.getMonth() + 1}/${d.getDate()}`;
  },

  /* ---------------------------------------------------------------
   * バイト数を「12.3 MB」のような読みやすい形にする。
   * 設定画面の使用容量表示に使う。
   * --------------------------------------------------------------- */
  formatBytes(bytes) {
    if (bytes == null) return '不明';
    if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(0) + ' KB';
    return (bytes / 1024 / 1024).toFixed(1) + ' MB';
  }
};
